const findActor = db.prepare("SELECT id FROM actors WHERE name = ?");
const insertActor = db.prepare("INSERT INTO actors (name) VALUES (?)");
const movieExists = db.prepare("SELECT id FROM movies WHERE id = ?");
const linkActor = db.prepare(
  "INSERT OR IGNORE INTO movie_actors (movie_id, actor_id, character_name) VALUES (?, ?, ?)",
);

// En transaktion: antingen går allt igenom, eller ingenting
const seed = db.transaction(() => {
  let newActors = 0;
  let newLinks = 0;

  for (const [movieId, cast] of Object.entries(casts)) {
    if (!movieExists.get(movieId)) {
      console.warn(`Movie ${movieId} not found, skipping`);
      continue;
    }

    for (const [name, character] of cast) {
      let actor = findActor.get(name);
      if (!actor) {
        const result = insertActor.run(name);
        actor = { id: result.lastInsertRowid };
        newActors++;
      }
      newLinks += linkActor.run(movieId, actor.id, character).changes;
    }
  }

  return { newActors, newLinks };
});

const { newActors, newLinks } = seed();
console.log(`Done! Added ${newActors} new actors and ${newLinks} new movie roles.`);
